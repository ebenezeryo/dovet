function makeBanner(text, shade, textSize) {
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    rows: [new TableRow({ children: [
      new TableCell({
        shading: shading(shade),
        width: { size: 9360, type: WidthType.DXA },
        children: [new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text, bold: true, size: textSize || 48, color: C.white })],
        })],
      }),
    ]})],
  });
}

function makeHintBox(hint) {
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    rows: [new TableRow({ children: [
      new TableCell({
        shading: shading(C.paleGold),
        width: { size: 9360, type: WidthType.DXA },
        borders: { left: { style: BorderStyle.THICK, size: 24, color: C.gold } },
        children: [
          new Paragraph({ children: [
            new TextRun({ text: '💡 Hint: ', bold: true, color: C.deepOrange, size: 20 }),
            new TextRun({ text: hint, color: C.nearBlack, size: 20 }),
          ]}),
        ],
      }),
    ]})],
  });
}

function makeOptionsTable(opts, correctIdx) {
  const letters = ['A','B','C','D'];
  const rows = opts.map((opt, i) => {
    const isCorrect = i === correctIdx;
    return new TableRow({ children: [
      new TableCell({
        shading: shading(isCorrect ? C.deepGreen : C.lightGrey),
        width: { size: 1200, type: WidthType.DXA },
        children: [boldPara(letters[i], 22, isCorrect ? C.white : C.darkGrey, AlignmentType.CENTER)],
      }),
      new TableCell({
        shading: shading(isCorrect ? C.paleGreen : C.white),
        width: { size: 8160, type: WidthType.DXA },
        borders: isCorrect ? { left: { style: BorderStyle.THICK, size: 12, color: C.deepGreen } } : {},
        children: [new Paragraph({ children: [
          new TextRun({ text: opt, size: 20, color: C.nearBlack }),
          ...(isCorrect ? [new TextRun({ text: '   ✓ CORRECT', bold: true, color: C.deepGreen, size: 20 })] : []),
        ]})],
      }),
    ]});
  });
  return new Table({ width: { size: 9360, type: WidthType.DXA }, rows });
}

function makeSolutionBox(steps, correctOpt) {
  const stepParas = steps.map((s, i) => new Paragraph({ children: [
    new TextRun({ text: `Step ${i+1}: `, bold: true, color: C.midGreen, size: 20 }),
    new TextRun({ text: s, color: C.nearBlack, size: 20 }),
  ]}));
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    rows: [new TableRow({ children: [
      new TableCell({
        shading: shading(C.paleGreen),
        width: { size: 9360, type: WidthType.DXA },
        borders: { left: { style: BorderStyle.THICK, size: 32, color: C.deepGreen } },
        children: [
          boldPara('📖 Step-by-step solution:', 20, C.deepGreen),
          ...stepParas,
          boldPara('✓ Answer: ' + correctOpt, 20, C.deepGreen),
        ],
      }),
    ]})],
  });
}

function buildDay(day) {
  const dayColour = DAY_COLOURS[day.name];
  const sections = [];

  // Day banner
  sections.push(makeBanner(day.name.toUpperCase(), dayColour, 76));
  sections.push(new Table({
    width: { size: 9360, type: WidthType.DXA },
    rows: [new TableRow({ children: [
      new TableCell({
        shading: shading(dayColour),
        width: { size: 9360, type: WidthType.DXA },
        children: [new Paragraph({
          alignment: AlignmentType.CENTER,
          children: [new TextRun({ text: day.subtopic, bold: true, size: 42, color: C.gold })],
        })],
      }),
    ]})],
  }));
  sections.push(new Paragraph({}));

  let qNum = 1;
  day.clusters.forEach((cluster, clIdx) => {
    // Cluster label
    sections.push(new Paragraph({ children: [
      new TextRun({ text: `Cluster ${clIdx+1}: ${cluster.topic}`, bold: true, size: 28, color: C.deepGreen }),
    ]}));

    cluster.questions.forEach(q => {
      const letters = ['A','B','C','D'];
      const isEx = q.isExample;
      const headerLeft = isEx ? `✅ SOLVED EXAMPLE ${q.exNum} OF 3` : `📝 PRACTICE QUESTION ${qNum}`;
      const headerShade = isEx ? C.midGreen : C.deepBlue;
      const bodyShade = isEx ? C.paleGreen : C.paleBlue;
      const bodyTextColour = isEx ? C.deepGreen : C.deepBlue;

      sections.push(new Paragraph({}));
      sections.push(twoColHeader(headerLeft, headerShade, cluster.topic, bodyShade));
      sections.push(boldPara(q.text, 24, C.nearBlack));
      sections.push(makeHintBox(q.hint));
      sections.push(makeOptionsTable(q.opts, q.correct));
      sections.push(makeSolutionBox(q.steps, q.opts[q.correct]));
      sections.push(new Paragraph({}));

      if (!isEx) qNum++;
    });
  });

  // Answer key
  sections.push(new Paragraph({}));
  sections.push(makeBanner(`📋 ${day.name.toUpperCase()} ANSWER KEY`, dayColour, 36));
  const letters = ['A','B','C','D'];
  let aqNum = 1;
  day.clusters.forEach(cluster => {
    cluster.questions.filter(q => !q.isExample).forEach(q => {
      sections.push(new Table({
        width: { size: 9360, type: WidthType.DXA },
        rows: [new TableRow({ children: [
          new TableCell({ shading: shading(C.lightGrey), width: { size: 800, type: WidthType.DXA },
            children: [boldPara(`Q${aqNum}`, 20, C.nearBlack)] }),
          new TableCell({ shading: shading(C.white), width: { size: 5560, type: WidthType.DXA },
            children: [plainPara(q.text.substring(0, 80) + (q.text.length > 80 ? '…' : ''), 18, C.nearBlack)] }),
          new TableCell({ shading: shading(C.paleGreen), width: { size: 500, type: WidthType.DXA },
            children: [boldPara(letters[q.correct], 20, C.deepGreen)] }),
          new TableCell({ shading: shading(C.white), width: { size: 2500, type: WidthType.DXA },
            children: [boldPara(q.opts[q.correct], 18, C.deepGreen)] }),
        ]})]
      }));
      aqNum++;
    });
  });

  return sections;
}

function buildGlossary() {
  const terms = [
    { term:'Algorithm', def:'A set of step-by-step instructions designed to solve a problem or complete a task.', ex:'A recipe for baking a cake is an algorithm.' },
    { term:'Sequence', def:'Steps carried out one after another in a fixed order.', ex:'Step 1: open bag. Step 2: take out book.' },
    { term:'Variable', def:'A named storage location in memory that holds a value which can change.', ex:'score = 10 (score can change as the game progresses).' },
    { term:'Constant', def:'A named value that is set once and never changes during the program.', ex:'CONSTANT MAX_LIVES = 3' },
    { term:'Input', def:'Data received by a program from an external source such as a user typing.', ex:'INPUT name — the user types their name.' },
    { term:'Output', def:'Data sent out of a program to be displayed or used externally.', ex:'OUTPUT "Hello, Chloe!" — displays on screen.' },
    { term:'Selection', def:'A structure that chooses between different actions based on a condition.', ex:'IF score >= 50 THEN OUTPUT "Pass"' },
    { term:'Iteration', def:'Repeating a block of steps — also called a loop.', ex:'FOR i = 1 TO 5: OUTPUT i' },
    { term:'FOR loop', def:'A loop that repeats a known, fixed number of times.', ex:'FOR i = 1 TO 10: OUTPUT i' },
    { term:'WHILE loop', def:'A loop that repeats as long as a condition is True.', ex:'WHILE lives > 0: play game' },
    { term:'Pseudocode', def:'A way of writing algorithm steps in plain English-like language — not a real programming language.', ex:'INPUT age\nIF age >= 11 THEN OUTPUT "Secondary"' },
    { term:'Trace Table', def:'A table used to track the value of each variable at every step of an algorithm — used to check it works correctly.', ex:'Columns: i | total. Rows: each iteration.' },
  ];

  const rows = terms.map(t => new TableRow({ children: [
    new TableCell({ shading: shading(C.midGreen), width: { size: 2000, type: WidthType.DXA },
      children: [boldPara(t.term, 20, C.white)] }),
    new TableCell({ shading: shading(C.paleGreen), width: { size: 4680, type: WidthType.DXA },
      children: [plainPara(t.def, 18, C.nearBlack)] }),
    new TableCell({ shading: shading(C.white), width: { size: 2680, type: WidthType.DXA },
      children: [plainPara(t.ex, 18, C.nearBlack)] }),
  ]}));

  const headerRow = new TableRow({ children: [
    new TableCell({ shading: shading(C.deepGreen), width: { size: 2000, type: WidthType.DXA },
      children: [boldPara('Term', 22, C.white)] }),
    new TableCell({ shading: shading(C.deepGreen), width: { size: 4680, type: WidthType.DXA },
      children: [boldPara('Definition', 22, C.white)] }),
    new TableCell({ shading: shading(C.deepGreen), width: { size: 2680, type: WidthType.DXA },
      children: [boldPara('Example', 22, C.white)] }),
  ]});

  return [
    new Paragraph({}),
    makeBanner('📖 KEY TERMS GLOSSARY', C.deepGreen, 36),
    new Table({ width: { size: 9360, type: WidthType.DXA }, rows: [headerRow, ...rows] }),
    new Paragraph({ children: [
      new TextRun({ text: `${AGENCY} · ${TOPIC} · ${YEAR}`, italics: true, size: 18, color: C.darkGrey }),
    ]}),
  ];
}

