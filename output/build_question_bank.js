// ── Helpers ────────────────────────────────────────────────
function shading(hex) {
  return { type: ShadingType.CLEAR, color: 'auto', fill: hex };
}
function cell(paragraphs, shade, width) {
  return new TableCell({
    shading: shading(shade),
    width: { size: width, type: WidthType.DXA },
    children: Array.isArray(paragraphs) ? paragraphs : [paragraphs],
  });
}
function boldPara(text, size, colour, align) {
  return new Paragraph({
    alignment: align || AlignmentType.LEFT,
    children: [new TextRun({ text, bold: true, size: size || 24, color: colour || C.nearBlack })],
  });
}
function plainPara(text, size, colour) {
  return new Paragraph({
    children: [new TextRun({ text, size: size || 22, color: colour || C.nearBlack })],
  });
}
function colourPara(runs) {
  return new Paragraph({ children: runs });
}
function pageBreak() {
  return new Paragraph({ children: [new PageBreak()] });
}
function twoColHeader(leftText, leftShade, rightText, rightShade) {
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    rows: [new TableRow({ children: [
      cell(boldPara(leftText, 22, C.white), leftShade, 3500),
      cell(boldPara(rightText, 22, C.nearBlack), rightShade, 5860),
    ]})],
  });
}

